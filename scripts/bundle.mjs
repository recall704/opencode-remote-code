#!/usr/bin/env node
/**
 * Produces the drop-in single-file build: `dist/plugins/remote-code.js`.
 *
 * OpenCode auto-discovers plugins by globbing `{plugin,plugins}/*.{ts,js}` —
 * files only, never sub-directories. A plugin *package* directory therefore has
 * to be registered manually in `opencode.json(c)` (`"plugin": ["./plugins/remote-code"]`),
 * while this bundled file only has to be copied into `~/.config/opencode/plugins/`.
 *
 * Everything except Node built-ins is inlined, including the prompt texts that
 * `src/prompts/index.ts` otherwise reads from disk next to itself, so the file
 * needs no `node_modules` and no sibling assets.
 */
import { build } from "esbuild"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const promptsDir = path.join(root, "src", "prompts")
const entry = path.join(root, "dist", "index.js")
const outfile = path.join(root, "dist", "plugins", "remote-code.js")

const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"))

/**
 * Replaces `dist/prompts/inline.js` (which is empty after `tsc`) with a
 * generated module holding the full text of every prompt file.
 */
const inlinePromptsPlugin = {
  name: "inline-prompts",
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /^\.\/inline\.js$/ }, (args) => {
      // Only rewrite the prompts loader; esbuild hands us the raw specifier.
      if (!/[\\/]prompts[\\/]index\.js$/.test(args.importer)) return null

      return {
        path: args.path,
        namespace: "inline-prompts",
      }
    })

    pluginBuild.onLoad({ filter: /.*/, namespace: "inline-prompts" }, () => {
      const entries = fs
        .readdirSync(promptsDir)
        .filter((file) => file.endsWith(".txt"))
        .sort()
        .map((file) => {
          const name = path.basename(file, ".txt")
          const text = fs.readFileSync(path.join(promptsDir, file), "utf8")
          return `  ${JSON.stringify(name)}: ${JSON.stringify(text)},`
        })

      return {
        contents: `export const INLINE_PROMPTS = {\n${entries.join("\n")}\n}\n`,
        loader: "js",
        resolveDir: promptsDir,
      }
    })
  },
}

/**
 * `ssh2` probes two optional native add-ons inside `try`/`catch` and falls back
 * to Node's `crypto` when they are missing. They cannot be bundled (binaries),
 * so they are left external: the runtime `require` fails and `ssh2` falls back.
 */
const optionalNativeModules = ["cpu-features", "./crypto/build/Release/sshcrypto.node"]

const result = await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  external: optionalNativeModules,
  plugins: [inlinePromptsPlugin],
  sourcemap: false,
  minify: false,
  logLevel: "warning",
  banner: {
    js: [
      "/**",
      ` * opencode-remote-code v${pkg.version} — self-contained single-file build.`,
      " * Generated by scripts/bundle.mjs — do not edit.",
      " * Install: cp dist/plugins/remote-code.js ~/.config/opencode/plugins/",
      " */",
      // esbuild wraps CJS `require()` / `__dirname` uses from bundled deps
      // (ssh2, diff) in helpers that assume a CommonJS scope. Bun provides both
      // natively; plain Node >= 20 ESM does not, so define them here to keep the
      // artifact loadable under either runtime.
      'import { createRequire as __createRequire } from "node:module";',
      'import { fileURLToPath as __fileURLToPath } from "node:url";',
      'import { dirname as __pathDirname } from "node:path";',
      "const require = /* @__PURE__ */ __createRequire(import.meta.url);",
      "const __filename = /* @__PURE__ */ __fileURLToPath(import.meta.url);",
      "const __dirname = /* @__PURE__ */ __pathDirname(__filename);",
    ].join("\n"),
  },
})

if (result.warnings.length > 0) {
  for (const warning of result.warnings) {
    console.warn(`[bundle] warning: ${warning.text}`)
  }
}

const bytes = fs.statSync(outfile).size
console.log(`[bundle] Wrote ${path.relative(root, outfile)} (${(bytes / 1024).toFixed(0)} KB)`)
